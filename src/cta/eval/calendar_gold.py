# ruff: noqa: E501  (long report strings)
"""Same-date rows of the calendar-only questions, and re-scoring stored runs (step 4a-2).

    uv run python -m cta.eval.calendar_gold      # writes docs/calendar-same-date.md

For every calendar-only question it lists the rows that share the date_start of a gold row (any term,
not the gold rows themselves, not rows that are only a "For more info" web address) with a proposed
yes/no for "may appear in an answer without penalty". The criterion, fixed: yes only if the event
text means the same thing as the gold row's event (same event, different wording). The proposals are
written below from the event texts and the questions only, never from router output.
"""

import json
import sys

from cta.eval import run_answers as ra
from cta.eval.questions import load_questions
from cta.eval.run_retrieval import RESULTS
from cta.graph.terms import link_row
from cta.settings import ROOT
from cta.validate.calendar import load_events_for_indexing

OUT = ROOT / "docs" / "calendar-same-date.md"
EVENTS = ROOT / "data" / "calendar" / "calendar_events.json"
# The owner's recommendation (pre-filled, 2026-10-12): the first listed row stays required, the
# second becomes an acceptable extra. Applied to eval/questions.jsonl only after the owner says so.
PREFILLED = {
    "q33": {"required": ["spring-2027-007"], "extra": ["spring-2027-006"]},
    "q63": {"required": ["winter-2027-004"], "extra": ["winter-2027-005"]},
}
# Proposals (colliding row id -> (yes/no, reason)), keyed by question, from event text only.
# Anything not listed here is "no": a different event on the same date.
PROPOSALS: dict[str, dict[str, tuple[str, str]]] = {
    "q63": {"winter-2027-005": ("yes", "'Classes begin' is the same event as 'Start of Winter 2027 session' (owner recommendation, pre-filled)")},
}  # fmt: skip
DEFAULT_REASON = "a different event that happens to fall on the same date"


def calendar_only(questions: list[dict]) -> list[dict]:
    return [q for q in questions if ra.gold_kind(q) == "calendar_only"]


def collisions(events: list[dict], gold_ids: list[str]) -> list[tuple[dict, str]]:
    """(row, the gold row it collides with) for every row with the same date_start as a gold row,
    in file order; gold rows, undated rows and web-address rows are excluded."""
    by_id = {e["id"]: e for e in events}
    found = []
    for e in events:
        if e["id"] in gold_ids or not e["date_start"] or link_row(e):
            continue
        for g in gold_ids:
            if by_id[g]["date_start"] == e["date_start"]:
                found.append((e, g))
                break
    return found


def proposal(qid: str, row_id: str) -> tuple[str, str]:
    return PROPOSALS.get(qid, {}).get(row_id, ("no", DEFAULT_REASON))


def with_prefilled(question: dict) -> dict:
    """The question as it would read after the owner's pre-filled recommendation (a copy)."""
    change = PREFILLED.get(question["id"])
    if not change:
        return question
    required = [g for g in question["gold_sources"] if g["id"] in change["required"]]
    return question | {"gold_sources": required, "calendar_acceptable_extra": change["extra"]}


def rescore(
    run: dict, questions: dict[str, dict], version: int
) -> dict[str, tuple[str, str | None]]:
    """question id -> (correctness, label) for the calendar-only questions of a stored run, from the
    rows it returned and its route. No model call."""
    out = {}
    for r in run["per_question"]:
        q = questions.get(r["id"])
        if q is None or ra.gold_kind(q) != "calendar_only":
            continue
        stub = type("Stored", (), {"row_ids": r["returned_rows"], "route": r["route"]})()
        verdict, label, _ = ra.calendar_result(q, stub, version)
        out[r["id"]] = (verdict["correctness"], label)
    return out


def render(events: list[dict], questions: list[dict], runs: list[dict]) -> str:
    by_id = {e["id"]: e for e in events}
    rows = calendar_only(questions)
    out = [
        "# Calendar-only questions: rows that share a date with a gold row",
        "",
        "Generated by `python -m cta.eval.calendar_gold` (step 4a-2). **Nothing here is applied to `eval/questions.jsonl`**; "
        "the owner's marks come first. For each calendar-only question (dev and test) the rows with the same `date_start` as one of its gold rows "
        '(any term; not the gold rows; not rows that are only a "For more info" web address) are listed with the gold row they collide with.',
        "",
        "**Criterion, fixed:** a collision is an *acceptable extra* (may appear in an answer without penalty) only if its event text means the same thing as the gold row's event "
        "(same event, different wording). The proposals use the event texts and the question only; no router output was used.",
        "",
        "## Owner recommendation, pre-filled (not applied yet)",
        "",
        "| question | required gold (stays) | becomes acceptable extra | reason |",
        "|---|---|---|---|",
        '| q33 | `spring-2027-007` "Classes begin" | `spring-2027-006` "Start of Spring 2027 term." (today both are required gold) | same date, same event in different words |',
        '| q63 | `winter-2027-004` "Start of Winter 2027 session." | `winter-2027-005` "Classes begin" (not gold today) | same date, same event in different words |',
        "",
        "## Collisions",
        "",
        "| question | colliding row | term | event | collides with | proposed acceptable extra | reason | owner: yes/no |",
        "|---|---|---|---|---|---|---|---|",
    ]
    quiet = []
    for q in rows:
        gold = [g["id"] for g in q["gold_sources"]]
        found = collisions(events, gold)
        if not found:
            quiet.append(q["id"])
        for e, g in found:
            yes_no, why = proposal(q["id"], e["id"])
            mark = (
                " (owner recommendation, pre-filled)"
                if (q["id"], e["id"]) in {("q63", "winter-2027-005")}
                else ""
            )
            out.append(
                f'| {q["id"]} ({q["split"]}) {q["question"]} | `{e["id"]}` | {e["term"]} | {e["event"]} | `{g}` "{by_id[g]["event"]}" | {yes_no}{mark} | {why} | |'
            )
    out += [
        "",
        f"No same-date collision: {', '.join(quiet)}. (q33's two gold rows share a date with each other; see the pre-filled table.)",
        "",
    ]
    questions_by_id = {q["id"]: q for q in questions}
    pre = {qid: with_prefilled(q) for qid, q in questions_by_id.items()}
    out += [
        "## The three stored 4a runs re-scored under scoring v2 (re-scored, not a decision)",
        "",
        "No model call. Scoring v2: the required gold rows must all be returned and nothing outside the required rows and the acceptable extras may be; "
        "here only the two pre-filled changes (q33, q63) are assumed, none of the owner's other marks. Scoring v1 is the exact-rows rule used in the 4a result, which stands as REJECT.",
        "",
        "| question | " + " | ".join(f"{r['label']} v1 / v2" for r in runs) + " |",
        "|---|" + "---|" * len(runs),
    ]
    ids = sorted(q["id"] for q in calendar_only([q for q in questions if q["split"] == "dev"]))
    v1 = [rescore(r, questions_by_id, 1) for r in runs]
    v2 = [rescore(r, pre, 2) for r in runs]
    for qid in ids:
        cells = [f"{a[qid][0]} / {b[qid][0]}" for a, b in zip(v1, v2, strict=True)]
        out.append(f"| {qid} | " + " | ".join(cells) + " |")
    summary = []
    for label, table in (("v1", v1), ("v2", v2)):
        counts = [sum(t[i][0] == "correct" for i in ids) for t in table]
        wrong = [sum(t[i][1] == "calendar wrong row" for i in ids) for t in table]
        summary.append(
            f"{label}: correct {counts} of {len(ids)} per run (mean {sum(counts) / len(counts):.1f}), wrong rows {wrong}"
        )
    out += ["", "- " + "\n- ".join(summary), ""]
    return "\n".join(out) + "\n"


def main() -> int:
    events = load_events_for_indexing(EVENTS)
    questions = load_questions()
    runs = [
        json.loads((RESULTS / f"router-run{i}.json").read_text(encoding="utf-8")) for i in (1, 2, 3)
    ]
    OUT.write_text(render(events, questions, runs), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
